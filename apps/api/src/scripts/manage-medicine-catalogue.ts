import { randomUUID } from 'node:crypto';
import { parseArgs } from 'node:util';
import { createDb } from '@dhc/db';
import { LocalFileStore } from '../files';
import { readBounded, readBoundedBytes } from '../modules/medicine-staging/directory';
import {
  recordCatalogueEvidence,
  revokeCatalogueEvidence,
  publishCatalogue,
  withdrawCatalogue,
} from '../modules/medicine-import/publication';

try {
  const { values } = parseArgs({
    options: {
      action: { type: 'string' },
      input: { type: 'string' },
      document: { type: 'string' },
      'operator-email': { type: 'string' },
      'evidence-id': { type: 'string' },
      reason: { type: 'string' },
      execute: { type: 'boolean' },
      'confirm-reviewed': { type: 'boolean' },
      help: { type: 'boolean' },
    },
    strict: true,
    allowPositionals: false,
  });
  if (values.help)
    process.stdout.write(
      'Owner catalogue controls: --action evidence|revoke|publish|withdraw --operator-email <active operator>. Supply --input <JSON> for evidence/publish/withdraw; --document <private approval file> for evidence; --evidence-id and --reason for revoke. Requires explicit owner DATABASE_URL and FILE_STORE_DIR. Publish/withdraw default to preview. Every write requires --execute --confirm-reviewed. No evidence is generated by this command.\n',
    );
  else {
    if (!process.env.DATABASE_URL || !process.env.FILE_STORE_DIR || !values['operator-email'])
      throw new Error('Supply the explicit owner DATABASE_URL, FILE_STORE_DIR and operator email.');
    if (!['evidence', 'revoke', 'publish', 'withdraw'].includes(values.action ?? ''))
      throw new Error('Choose an action; use --help.');
    if (
      (values.execute || values.action === 'evidence' || values.action === 'revoke') &&
      (!values.execute || !values['confirm-reviewed'])
    )
      throw new Error(
        'Every write needs explicit --execute --confirm-reviewed after reviewing the request and supporting evidence.',
      );
    const input = values.input ? JSON.parse(await readBounded(values.input, 128 * 1024)) : null;
    const document =
      values.action === 'evidence' && values.document
        ? await readBoundedBytes(values.document, 5 * 1024 * 1024)
        : null;
    const db = createDb(process.env.DATABASE_URL),
      files = new LocalFileStore(process.env.FILE_STORE_DIR);
    try {
      const op = await db.platformOperator.findUnique({
        where: { email: values['operator-email'].trim().toLowerCase() },
      });
      if (!op) throw new Error('The owning platform operator does not exist.');
      const source = {
        id: randomUUID(),
        ip: '127.0.0.1',
        headers: { 'user-agent': 'dhc-owner-catalogue-control' },
      };
      const result =
        values.action === 'evidence'
          ? await recordCatalogueEvidence(
              db,
              files,
              op.id,
              source,
              input,
              document ?? Buffer.alloc(0),
            )
          : values.action === 'revoke'
            ? await revokeCatalogueEvidence(
                db,
                op.id,
                source,
                values['evidence-id'] ?? '',
                values.reason ?? '',
              )
            : values.action === 'publish'
              ? await publishCatalogue(db, files, op.id, source, input, values.execute ?? false)
              : await withdrawCatalogue(db, op.id, source, input, values.execute ?? false);
      process.stdout.write(JSON.stringify(result, null, 2) + '\n');
    } finally {
      await db.$disconnect();
    }
  }
} catch (error) {
  console.error(
    error instanceof Error && error.constructor === Error
      ? error.message
      : 'Catalogue action refused; no partial clinical changes were committed.',
  );
  process.exitCode = 1;
}
