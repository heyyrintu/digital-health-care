interface Operation {
  method: 'get' | 'post' | 'put' | 'patch' | 'delete';
  path: string;
  operationId: string;
  summary: string;
  /** Endpoints without auth are listed explicitly; everything else needs a bearer token. */
  public?: boolean;
  /** Platform console: a platform operator's token (its own audience), never a clinic one. */
  platform?: boolean;
  body?: z.ZodType;
  query?: z.ZodObject;
  /** UUIDs, unless given with their own schema (a public page's slug). */
  pathParams?: (string | { name: string; schema: Record<string, unknown> })[];
  response?: z.ZodType;
  /** Success status; defaults to 200. 204 has no body. */
  status?: 200 | 201 | 204;
  /** The response is a PDF file instead of JSON. */
  pdf?: boolean;
  zip?: boolean;
  csv?: boolean;
  /**
   * The request body is a file (an uploaded result, `logo`: a PNG, JPEG or WebP logo, or
   * `document`: a PDF, JPEG, PNG or WebP document).
   */
  upload?: boolean | 'logo' | 'document';
  /** The response is an uploaded file (PDF or image, `logo` or `document`) instead of JSON. */
  file?: boolean | 'logo' | 'document';
  /** For a 201 that a retry answers with 200 and the same body: what that 200 means. */
  replay?: string;
}

