/** Uploaded results: the file itself as the body, in any type a clinic may accept. */
const binary = Object.fromEntries(
  Object.values(UPLOAD_MEDIA_TYPES)
    .flat()
    .map((type) => [type, { schema: { type: 'string', format: 'binary' } }]),
);

/** Document files: PDF, JPEG, PNG or WebP. */
const documentBinary = Object.fromEntries(
  Object.values(DOCUMENT_MEDIA_TYPES).map((type) => [
    type,
    { schema: { type: 'string', format: 'binary' } },
  ]),
);

const logoBinary = Object.fromEntries(
  Object.values(LOGO_MEDIA_TYPES).map((type) => [
    type,
    { schema: { type: 'string', format: 'binary' } },
  ]),
);

export function buildOpenApiDocument(options: { version: string; serverUrl?: string }) {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const op of operations) {
    const status = op.status ?? 200;
    const parameters = [
      ...(op.pathParams ?? []).map((param) => ({
        name: typeof param === 'string' ? param : param.name,
        in: 'path',
        required: true,
        schema: typeof param === 'string' ? { type: 'string', format: 'uuid' } : param.schema,
      })),
      ...queryParameters(op.query),
    ];
    paths[op.path] ??= {};
    paths[op.path]![op.method] = {
      operationId: op.operationId,
      summary: op.summary,
      ...(op.public ? { security: [] } : op.platform ? { security: [{ platformAuth: [] }] } : {}),
      ...(parameters.length ? { parameters } : {}),
      ...(op.body
        ? {
            requestBody: {
              required: true,
              content: { 'application/json': { schema: toSchema(op.body, 'input') } },
            },
          }
        : {}),
      ...(op.upload
        ? {
            requestBody: {
              required: true,
              content:
                op.upload === 'logo'
                  ? logoBinary
                  : op.upload === 'document'
                    ? documentBinary
                    : binary,
            },
          }
        : {}),
      responses: {
        [String(status)]: op.csv
          ? {
              description: 'Private reconciliation CSV (integer INR paise)',
              content: { 'text/csv': { schema: { type: 'string', format: 'binary' } } },
            }
          : op.zip
            ? {
                description: 'Private patient-facing data ZIP',
                content: { 'application/zip': { schema: { type: 'string', format: 'binary' } } },
              }
            : op.pdf
              ? {
                  description: 'PDF',
                  content: { 'application/pdf': { schema: { type: 'string', format: 'binary' } } },
                }
              : op.file
                ? {
                    description: 'The file, as uploaded',
                    content:
                      op.file === 'logo'
                        ? logoBinary
                        : op.file === 'document'
                          ? documentBinary
                          : binary,
                  }
                : status === 204 || !op.response
                  ? { description: 'No content' }
                  : {
                      description: status === 201 ? 'Created' : 'OK',
                      content: { 'application/json': { schema: toSchema(op.response) } },
                    },
        ...(op.replay && op.response
          ? {
              '200': {
                description: op.replay,
                content: { 'application/json': { schema: toSchema(op.response) } },
              },
            }
          : {}),
        default: errorResponse,
      },
    };
  }

  return {
    openapi: '3.1.0',
    info: { title: 'Digital Healthcare Platform API', version: options.version },
    servers: options.serverUrl ? [{ url: options.serverUrl }] : [],
    paths,
    components: {
      schemas: { ErrorResponse: toSchema(ErrorResponse) },
      securitySchemes: {
        bearerAuth: { type: 'http', scheme: 'bearer' },
        // Platform console tokens: a separate audience and key; clinic tokens are refused.
        platformAuth: { type: 'http', scheme: 'bearer' },
      },
    },
    security: [{ bearerAuth: [] }],
  };
}

function queryParameters(query: z.ZodObject | undefined) {
  if (!query) return [];
  const schema = toSchema(query, 'input') as {
    properties?: Record<string, unknown>;
    required?: string[];
  };
  return Object.entries(schema.properties ?? {}).map(([name, prop]) => ({
    name,
    in: 'query',
    required: schema.required?.includes(name) ?? false,
    schema: prop,
  }));
}

/** JSON Schema 2020-12 (the dialect OpenAPI 3.1 uses), without the top-level `$schema`. */
function toSchema(schema: z.ZodType, io: 'input' | 'output' = 'output') {
  const { $schema: _schema, ...rest } = z.toJSONSchema(schema, { io, unrepresentable: 'any' });
  return rest;
}
